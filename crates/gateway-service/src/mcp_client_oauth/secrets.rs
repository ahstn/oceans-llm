use std::{sync::OnceLock, time::Duration};

use base64::{Engine as _, engine::general_purpose::URL_SAFE_NO_PAD};
use sha2::{Digest, Sha256};
use tokio::sync::Semaphore;

use super::error::OauthError;

/// Argon2 runs at most this many at a time for the public OAuth endpoints.
const MAX_CONCURRENT_ARGON2: usize = 4;
/// How long a request waits for an Argon2 slot before getting `503`.
const ARGON2_SLOT_WAIT: Duration = Duration::from_secs(5);

const TOKEN_BYTES: usize = 32;

/// A 256-bit random token, base64url-encoded behind `prefix`.
#[must_use]
pub(crate) fn generate_token(prefix: &str) -> String {
    let mut bytes = [0_u8; TOKEN_BYTES];
    rand::fill(&mut bytes);
    format!("{prefix}{}", URL_SAFE_NO_PAD.encode(bytes))
}

/// The lookup key stored for an access token, refresh token, or code.
///
/// These are 256-bit random values generated by [`generate_token`], so a
/// fast digest is enough: there is nothing to brute-force. Argon2 is kept for
/// client secrets and API keys.
#[must_use]
pub fn oauth_token_hash(token: &str) -> String {
    let digest = Sha256::digest(token.as_bytes());
    digest.iter().map(|byte| format!("{byte:02x}")).collect()
}

const CLIENT_SECRET_HASH_PREFIX: &str = "sha256:";

/// The stored hash of a client secret the gateway generated.
///
/// Generated secrets are 256-bit random tokens, like access tokens, so a fast
/// digest is enough. Registration is open to anyone, and hashing with Argon2
/// there let a flood of registrations take the Argon2 slots that client
/// authentication needs.
#[must_use]
pub(crate) fn hash_client_secret(secret: &str) -> String {
    format!("{CLIENT_SECRET_HASH_PREFIX}{}", oauth_token_hash(secret))
}

/// Checks a secret against a [`hash_client_secret`] hash in constant time.
/// `None` for a hash in another format: an Argon2 hash from a client
/// registered before secrets were hashed this way.
#[must_use]
pub(crate) fn client_secret_matches(secret: &str, stored: &str) -> Option<bool> {
    let expected = stored.strip_prefix(CLIENT_SECRET_HASH_PREFIX)?;
    let actual = oauth_token_hash(secret);
    Some(
        expected.len() == actual.len()
            && expected
                .bytes()
                .zip(actual.bytes())
                .fold(0u8, |acc, (left, right)| acc | (left ^ right))
                == 0,
    )
}

/// Runs Argon2 work for client authentication.
///
/// Only clients registered before secrets were hashed with SHA-256 still need
/// it. The endpoints are reachable without an Oceans credential, and Argon2 is
/// deliberately CPU- and memory-hard. The work therefore runs on the blocking
/// pool, a few at a time, so a flood of requests queues briefly and then gets
/// `temporarily_unavailable` instead of starving the async executor.
pub(crate) async fn run_argon2<T, F>(work: F) -> Result<T, OauthError>
where
    T: Send + 'static,
    F: FnOnce() -> T + Send + 'static,
{
    static SLOTS: OnceLock<Semaphore> = OnceLock::new();
    let slots = SLOTS.get_or_init(|| Semaphore::new(MAX_CONCURRENT_ARGON2));
    run_limited(slots, ARGON2_SLOT_WAIT, work).await
}

/// Runs `work` on the blocking pool once a slot frees up. The slot moves into
/// the blocking task, so a caller that disconnects mid-hash cannot release it
/// while the hash is still running.
async fn run_limited<T, F>(
    slots: &'static Semaphore,
    wait: Duration,
    work: F,
) -> Result<T, OauthError>
where
    T: Send + 'static,
    F: FnOnce() -> T + Send + 'static,
{
    let slot = tokio::time::timeout(wait, slots.acquire())
        .await
        .map_err(|_| OauthError::temporarily_unavailable("the authorization server is busy"))?
        .map_err(|_| OauthError::server_error("credential hashing is unavailable"))?;
    tokio::task::spawn_blocking(move || {
        let _slot = slot;
        work()
    })
    .await
    .map_err(|_| OauthError::server_error("credential hashing failed"))
}

/// RFC 7636 S256: `BASE64URL(SHA256(code_verifier)) == code_challenge`.
#[must_use]
pub(crate) fn pkce_s256_matches(code_verifier: &str, code_challenge: &str) -> bool {
    if !is_valid_code_verifier(code_verifier) {
        return false;
    }
    let computed = URL_SAFE_NO_PAD.encode(Sha256::digest(code_verifier.as_bytes()));
    constant_time_eq(computed.as_bytes(), code_challenge.as_bytes())
}

/// RFC 7636 section 4.1: 43 to 128 unreserved characters.
fn is_valid_code_verifier(value: &str) -> bool {
    (43..=128).contains(&value.len())
        && value
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'.' | b'_' | b'~'))
}

/// A code challenge is the base64url form of a SHA-256 digest: 43 characters.
#[must_use]
pub(crate) fn is_valid_s256_challenge(value: &str) -> bool {
    value.len() == 43
        && value
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'_'))
}

fn constant_time_eq(left: &[u8], right: &[u8]) -> bool {
    left.len() == right.len()
        && left
            .iter()
            .zip(right)
            .fold(0_u8, |acc, (a, b)| acc | (a ^ b))
            == 0
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn client_secrets_hash_with_sha256_and_leave_argon2_hashes_to_argon2() {
        let hash = hash_client_secret("ocs_secret");
        assert!(hash.starts_with("sha256:"));
        assert_eq!(client_secret_matches("ocs_secret", &hash), Some(true));
        assert_eq!(client_secret_matches("ocs_other", &hash), Some(false));
        assert_eq!(
            client_secret_matches("ocs_secret", "$argon2id$v=19$m=19456,t=2,p=1$x$y"),
            None
        );
    }

    #[test]
    fn generated_tokens_are_prefixed_and_unique() {
        let first = generate_token("oat_");
        let second = generate_token("oat_");
        assert!(first.starts_with("oat_"));
        assert_eq!(first.len(), 4 + 43);
        assert_ne!(first, second);
        assert_eq!(oauth_token_hash(&first).len(), 64);
    }

    #[tokio::test]
    async fn a_cancelled_caller_keeps_its_slot_until_the_work_finishes() {
        let slots: &'static Semaphore = Box::leak(Box::new(Semaphore::new(1)));
        let (started_tx, started_rx) = std::sync::mpsc::channel();
        let (release_tx, release_rx) = std::sync::mpsc::channel::<()>();
        let caller = tokio::spawn(run_limited(slots, Duration::from_secs(5), move || {
            started_tx.send(()).unwrap();
            release_rx.recv().unwrap();
        }));
        tokio::task::spawn_blocking(move || started_rx.recv().unwrap())
            .await
            .unwrap();

        // The caller goes away while the hash runs; the slot stays taken.
        caller.abort();
        let _ = caller.await;
        assert_eq!(slots.available_permits(), 0);
        let busy = run_limited(slots, Duration::from_millis(20), || ()).await;
        assert_eq!(busy.unwrap_err().error, "temporarily_unavailable");

        release_tx.send(()).unwrap();
        let freed = tokio::time::timeout(Duration::from_secs(5), slots.acquire())
            .await
            .expect("the slot is released when the work finishes");
        drop(freed);
    }

    #[test]
    fn pkce_matches_the_rfc_7636_example() {
        let verifier = "dBjftJeZ4CVP-mB92K27uhbUJU1p1r_wW1gFWFOEjXk";
        let challenge = "E9Melhoa2OwvFrEMTJguCHaoeK1t8URWbuGJSstw-cM";
        assert!(is_valid_s256_challenge(challenge));
        assert!(pkce_s256_matches(verifier, challenge));
        assert!(!pkce_s256_matches(
            "dBjftJeZ4CVP-mB92K27uhbUJU1p1r_wW1gFWFOEjXX",
            challenge
        ));
        assert!(!pkce_s256_matches("short", challenge));
    }
}
